#!/bin/sh
# Prepare a git worktree so it can run next to the main checkout and other worktrees.
#
#   scripts/worktree-setup.sh [slot] [--no-services]
#
# Each worktree gets a slot (1-9). The slot picks its own ports and Docker Compose project, so
# every worktree has a separate Postgres, Mailpit and dev server. The main checkout is slot 0 and
# keeps the default ports. Without a slot argument the lowest slot no other worktree uses is taken.
set -eu

cd "$(dirname "$0")/.."
root=$(pwd -P)
marker='# Generated by scripts/worktree-setup.sh'

slot=""
services=yes
for argument in "$@"; do
  case "$argument" in
    --no-services) services=no ;;
    [1-9]) slot=$argument ;;
    *)
      printf '%s\n' "Usage: $0 [slot 1-9] [--no-services]" >&2
      exit 2
      ;;
  esac
done

main=$(git worktree list --porcelain | sed -n '1s/^worktree //p')
if [ "$root" = "$main" ]; then
  printf '%s\n' "This is the main checkout (slot 0). It uses the default ports, nothing to set up."
  exit 0
fi

if [ -e .env ] && ! grep -q "^$marker" .env; then
  printf '%s\n' ".env exists and was not generated by this script. Move it away first." >&2
  exit 1
fi

if [ -z "$slot" ]; then
  slot=$(sed -n 's/^WORKTREE_SLOT=//p' .env 2>/dev/null | tail -n 1)
fi

if [ -z "$slot" ]; then
  taken=" "
  for other in $(git worktree list --porcelain | sed -n 's/^worktree //p'); do
    [ "$other" = "$root" ] && continue
    value=$(sed -n 's/^WORKTREE_SLOT=//p' "$other/.env" 2>/dev/null | tail -n 1)
    taken="$taken$value "
  done
  for candidate in 1 2 3 4 5 6 7 8 9; do
    case "$taken" in *" $candidate "*) ;; *)
      slot=$candidate
      break
      ;;
    esac
  done
  if [ -z "$slot" ]; then
    printf '%s\n' "All slots 1-9 are taken. Remove a worktree with scripts/worktree-teardown.sh." >&2
    exit 1
  fi
fi

app_port=$((3000 + slot))
cat >.env <<EOF
$marker. Git-ignored and local to this worktree.
WORKTREE_SLOT=$slot
COMPOSE_PROJECT_NAME=jts-slot-$slot
COMPOSE_BIND_ADDRESS=127.0.0.1
POSTGRES_HOST_PORT=$((5433 + slot))
SMTP_HOST_PORT=$((587 + slot))
MAILPIT_HOST_PORT=$((8125 + slot))
PORT=$app_port
BASE_URL=http://localhost:$app_port
DATABASE_PORT=$((5433 + slot))
SMTP_PORT=$((587 + slot))
EOF

# Personal overrides (for example credentials injected locally) are shared, not copied.
if [ ! -e .env.local ] && [ -e "$main/.env.local" ]; then
  ln -s "$main/.env.local" .env.local
fi

pnpm install --frozen-lockfile

if [ "$services" = yes ]; then
  if command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; then
    docker compose up --detach --wait
  else
    printf '%s\n' "Docker is not available, so Postgres and Mailpit were not started."
  fi
fi

cat <<EOF

Worktree slot $slot is ready:
  app      http://localhost:$app_port/verhandlungstermin-finder/   (pnpm dev)
  mailpit  http://localhost:$((8125 + slot))
  postgres localhost:$((5433 + slot))
  e2e      pnpm test:e2e runs in its own Compose project (jts-e2e-$slot)
EOF
